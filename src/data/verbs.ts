// ---------------------------------------------------------------------------
// The 40 highest-frequency irregular Italian verbs, with full conjugations for
// the seven tenses the app drills. Forms are standard modern Italian.
//
// Notes on conventions:
//  - `passatoProssimo` uses masculine agreement for essere-auxiliary verbs
//    (io sono andato ...), which is the usual dictionary presentation.
//  - `imperativo` has no first-person singular, so its `io` slot is "".
//    The Lei / Loro (formal) forms occupy the `lui` / `loro` slots.
//  - A few modal verbs (potere, dovere, volere) lack a common imperative;
//    their imperativo slots are left empty.
// ---------------------------------------------------------------------------

import type { Conjugation, VerbEntry } from "@/lib/types";

const c = (
  io: string,
  tu: string,
  lui: string,
  noi: string,
  voi: string,
  loro: string,
): Conjugation => ({ io, tu, lui, noi, voi, loro });

/** Passato prossimo with the avere auxiliary (participle invariant). */
const avere = (pp: string): Conjugation =>
  c(`ho ${pp}`, `hai ${pp}`, `ha ${pp}`, `abbiamo ${pp}`, `avete ${pp}`, `hanno ${pp}`);

/** Passato prossimo with the essere auxiliary, masculine agreement. */
const essere = (sing: string, plur: string): Conjugation =>
  c(
    `sono ${sing}`,
    `sei ${sing}`,
    `è ${sing}`,
    `siamo ${plur}`,
    `siete ${plur}`,
    `sono ${plur}`,
  );

